/** A layer as its full 32 rows. */
const full = (l) => {
  const g = Array.from({ length: FACE }, () => ".".repeat(FACE));
  l.rows.forEach((r, i) => { g[l.y + i] = r; });
  return g;
};
/** Pixels of a layer as [x, y, letter]. */
const pixels = (l) => full(l).flatMap((row, y) => [...row].map((c, x) => [x, y, c]).filter(([, , c]) => c !== "."));
const ALL = { back0: BACK[0], back1: BACK[1], body: BODY, head: HEAD, front0: FRONT[0], front1: FRONT[1], ...EYES, ...BLUSH, ...MOUTHS, ...PROPS };

test("pixel Yuki is the app's: synced layers 32 wide in her palette, the app commit named; outlines never pure black", () => {
  assert.match(YUKI_FACES_SOURCE.commit, /^[0-9a-f]{7,40}$/);
  assert.match(YUKI_FACES_SOURCE.date, /^\d{4}-\d{2}-\d{2}$/);
  assert.equal(FACE, 32);
  for (const [name, l] of Object.entries(ALL)) {
    assert.ok(l.y >= 0 && l.y + l.rows.length <= FACE, `${name}: inside the bust`);
    for (const row of l.rows) {
      assert.equal(row.length, FACE, `${name}: 32 wide`);
      for (const ch of row) assert.ok(ch === "." || ch in PALETTE, `${name}: unknown letter "${ch}"`);
    }
  }
  for (const c of Object.values(PALETTE)) assert.match(c, /^#[0-9a-f]{6}$/);
  // outlines (hair O, skin q, outfit u) are a darker hue of their colour; the lid (K) is the only near-black
  for (const k of ["O", "q", "u"]) assert.notEqual(PALETTE[k], "#000000", k);
  const dark = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).reduce((a, b) => a + b) < 120;
  assert.deepEqual(Object.keys(PALETTE).filter((k) => dark(PALETTE[k])), ["K"]);
  // the generated file says where it came from and is never edited by hand
  assert.match(read("./yuki-faces.ts"), /^\/\/ GENERATED by tools\/yuki-faces\/sync\.mjs from the YUKI app at [0-9a-f]+/);
});

test("pixel Yuki's face is built like Dex's references: a lid that flicks out, a 3-tone iris dark to bright, a highlight, no lower lash, no nose, a tiny mouth, blush under the eyes", () => {
  const open = pixels(EYES.open);
  for (const side of [0, 1]) {
    // each eye's pixels (the left eye left of the middle)
    const eye = open.filter(([x]) => (side ? x >= 16 : x < 16));
    const rows = [...new Set(eye.map(([, y]) => y))].sort((a, b) => a - b);
    const lid = eye.filter(([, , c]) => c === "K");
    const top = Math.min(...lid.map(([, y]) => y));
    // the lid: a dark run on its top row, its outer end flicking out a pixel past the eye and a row down
    assert.ok(lid.filter(([, y]) => y === top).length >= 4, "a lid at least 4 wide");
    const outer = side ? Math.max(...eye.map(([x]) => x)) : Math.min(...eye.map(([x]) => x));
    assert.ok(lid.some(([x, y]) => x === outer && y === top + 1), "the flick: the outer corner a row down");
    // no lower lash: nothing dark under the lid's two rows
    assert.ok(!lid.some(([, y]) => y > top + 1), "no lower lash");
    // the iris: dark at the top to bright at the bottom (e/i, j, k), a white highlight in it
    const tone = (c) => ({ e: 0, i: 1, j: 2, k: 3 })[c];
    const iris = eye.filter(([, , c]) => tone(c) !== undefined);
    const mean = (y) => {
      const t = iris.filter(([, yy]) => yy === y).map(([, , c]) => tone(c));
      return t.reduce((a, b) => a + b, 0) / t.length;
    };
    const irisRows = rows.filter((y) => iris.some(([, yy]) => yy === y));
    assert.ok(irisRows.length >= 3, "a tall iris");
    assert.ok(mean(irisRows[0]) < mean(irisRows.at(-1)), "dark on top, bright below");
    assert.equal(new Set(iris.map(([, , c]) => c).filter((c) => "ijk".includes(c))).size, 3, "three tones");
    assert.ok(eye.some(([, , c]) => c === "W"), "a white highlight");
    // blush right under the outer half of the eye
    const blush = pixels(BLUSH.soft).filter(([x]) => (side ? x >= 16 : x < 16));
    assert.equal(blush.length, 2);
    for (const [x] of blush) assert.ok(side ? x >= outer - 2 && x <= outer : x <= outer + 2 && x >= outer, "under its outer half");
  }
  // a tiny mouth (two pixels), and no nose: between the eyes and the mouth only skin
  assert.ok(pixels(MOUTHS.small).length <= 2);
  const head = full(HEAD);
  const eyeBottom = Math.max(...open.map(([, y]) => y));
  const mouthTop = Math.min(...pixels(MOUTHS.small).map(([, y]) => y));
  for (let y = eyeBottom + 1; y < mouthTop; y++) for (let x = 13; x <= 18; x++) assert.equal(head[y][x], "f", `skin at ${x},${y}`);
  // bangs over the brows and the tops of the eyes, with one lighter band (L) in the hair
  assert.ok(head.slice(4, 10).join("").includes("L"), "a light band");
  const lidTop = Math.min(...open.filter(([, , c]) => c === "K").map(([, y]) => y));
  assert.match(head[lidTop - 1], /[HS]/, "bangs reach the lids");
});

test("pixel Yuki's layers: eyes, blush and mouth in their own rows over the bare head; a glance only moves the iris", () => {
  const rowsOf = (l) => l.rows.map((_, i) => l.y + i).filter((y) => /[^.]/.test(full(l)[y]));
  const blushY = BLUSH.soft.y;
  for (const k of YUKI_EYES) for (const y of rowsOf(EYES[k])) assert.ok(y < blushY, `eyes ${k} above the blush`);
  for (const k of YUKI_MOUTHS) for (const y of rowsOf(MOUTHS[k])) assert.ok(y > blushY, `mouth ${k} below the blush`);
  // a glance keeps the lids where they are and moves only the iris inside the eye
  for (const g of ["open-l", "open-r"]) {
    const a = pixels(EYES.open), b = pixels(EYES[g]);
    assert.deepEqual(a.filter(([, , c]) => c === "K"), b.filter(([, , c]) => c === "K"), `${g}: lids stay`);
    assert.notDeepEqual(a, b, `${g}: the iris moves`);
  }
  // every face the site shows has its layers; the blush turns strong with the app's strong-blush faces
  for (const [name, e] of Object.entries(EXPRESSIONS)) {
    if (!YUKI_EYES.includes(e.eyes)) continue;
    assert.equal(STRONG_BLUSH.includes(e.eyes), e.blush === "strong", `${name}: its blush`);
  }
  assert.deepEqual([...OPEN_EYES], ["open", "wide"]);
});

