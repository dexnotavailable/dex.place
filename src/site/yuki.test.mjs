/** A section of the page by its class, up to its end. */
const sectionOf = (html, cls) => {
  const at = html.indexOf(`<section class="yks ${cls}"`);
  return at < 0 ? "" : html.slice(at, html.indexOf("</section>", at) + "</section>".length);
};

