test("pixel Yuki moves on the app's clock (YUKI ui/mascotFrames.ts, synced as TIMING): frames, bob, blink, hop, press", () => {
  const css = read("./styles/yuki.css");
  const secs = (ms) => `${+(ms / 1000).toFixed(3)}s`.replace(".", "\\.");
  // two sprite frames of frameMs each, the bob twice as long
  assert.match(css, new RegExp(`\\.yk \\.yk__fa \\{ animation: yk-fa ${secs(YUKI_TIMING.frameMs * 2)} steps\\(1, end\\) infinite; \\}`));
  assert.match(css, new RegExp(`\\.yk \\.yk__bob \\{ animation: yk-bob ${secs(YUKI_TIMING.bobMs * 2)} steps\\(1, end\\) infinite; \\}`));
  // the blink: half, shut, half at the default clock's length, each within 5 ms of the app's
  const clock = 5.2;
  const keys = (name) => [...css.match(new RegExp(`@keyframes ${name} \\{([^\\n]*)\\}`))[1].matchAll(/([\d.]+)% \{ (?:visibility|opacity): (\w+); \}/g)].map((m) => +m[1]);
  const shut = keys("yk-blink-shut");
  const half = keys("yk-blink-half");
  const [[, halfMs], [, shutMs]] = YUKI_TIMING.blinkSteps;
  const ms = (a, b) => ((b - a) / 100) * clock * 1000;
  assert.ok(Math.abs(ms(half[1], half[2]) - halfMs) <= 5, "first half");
  assert.ok(Math.abs(ms(shut[1], shut[2]) - shutMs) <= 5, "shut");
  assert.ok(Math.abs(ms(half[3], 100) - halfMs) <= 5, "second half");
  assert.match(css, /\.yk\[data-eyes="open"\] \.yk__e--open \{ animation: yk-blink-open var\(--blink, 5\.2s\) steps\(1, end\) var\(--blink-at, 0s\) infinite; \}/);
  // the hop: hopMs long, the app's steps (whole pixels), the ahoge trailing it on frame B
  assert.match(css, new RegExp(`\\.yk\\.is-hop \\.yk__hop \\{ animation: yk-hop ${YUKI_TIMING.hopMs.hover}ms steps\\(1, end\\); \\}`));
  const hop = css.match(/@keyframes yk-hop \{([^\n]*)\}/)[1];
  for (const [t, dy] of YUKI_TIMING.hopSteps) assert.ok(hop.includes(`${Math.round(t * 100)}% { translate: 0 ${dy ? `${dy}px` : 0}; }`), `hop ${t}`);
  const sway = css.match(/@keyframes yk-hop-b \{([^\n]*)\}/)[1];
  for (const [t, f] of YUKI_TIMING.hopSway) assert.ok(sway.includes(`${Math.round(t * 100)}% { visibility: ${f ? "visible" : "hidden"}; }`), `sway ${t}`);
  // a press sinks the head a pixel (the app's PRESS.sink), letting go pops it a pixel up for popMs (motion/yuki.ts)
  assert.match(css, new RegExp(`\\.yk\\.is-press \\.yk__bob \\{ translate: 0 ${YUKI_TIMING.press.sink}px; \\}`));
  assert.match(css, new RegExp(`\\.yk\\.is-pop \\.yk__bob \\{ translate: 0 -${YUKI_TIMING.press.popPx}px; \\}`));
  const ts = read("./motion/yuki.ts");
  assert.match(ts, /YUKI_TIMING\.press\.popMs/);
  // a new face arrives behind a blink (the app's SWAP_STEPS)
  assert.match(ts, /YUKI_TIMING\.swapSteps/);
});

test("pixel Yuki's clocks: seeded per stage and per Yuki (a blink every 4.1 to 6.3 s, a look aside every 13 to 19 s), so two on one screen are out of step", () => {
  const clock = (html) => {
    const m = html.match(/--blink:([\d.]+)s;--blink-at:(-?[\d.]+)s;--look:([\d.]+)s;--look-at:(-?[\d.]+)s/);
    return m ? m.slice(1).map(Number) : null;
  };
  // the stages where she shows (render/cardart.ts, downloads.ts and yuki.ts seed them by place)
  const seeds = ["yuki-page", "yuki-dl", "yuki-card", "yuki-pban__cart"];
  const clocks = seeds.map((seed) => clock(yukiStage({ cols: 72, rows: 50, seed })));
  for (const [i, c] of clocks.entries()) {
    assert.ok(c, `${seeds[i]}: a clock`);
    assert.ok(c[0] >= 4.1 && c[0] <= 6.3, `${seeds[i]}: blink ${c[0]} s`);
    assert.ok(c[1] <= 0 && -c[1] <= c[0], `${seeds[i]}: starts inside its period`);
    assert.ok(c[2] >= 13 && c[2] <= 19, `${seeds[i]}: look ${c[2]} s`);
    assert.ok(c[3] <= 0 && -c[3] <= c[2], `${seeds[i]}: looks from inside its period`);
  }
  assert.equal(new Set(clocks.map((c) => c[0])).size, seeds.length, "each place its own period");
  assert.deepEqual(clock(yukiStage({ cols: 72, rows: 50, seed: "yuki-page" })), clocks[0], "the same on every build");
  // a night with no Yuki has no clock; a Yuki on her own takes hers from her seed, else her stage's
  assert.equal(clock(yukiStage({ cols: 72, rows: 50, seed: "x", layer: "back" })), null);
  assert.ok(clock(yukiSprite({ seed: "tile" })));
  assert.equal(clock(yukiSprite()), null);
  assert.equal(blinkVars("a"), blinkVars("a"));
  // the CSS reads both (period and start) on the open eyes and the blink's layers alike, and the look on the glances
  const css = read("./styles/yuki.css");
  for (const [k, name] of [["open", "yk-blink-open"], ["half", "yk-blink-half"], ["closed", "yk-blink-shut"]]) {
    assert.match(css, new RegExp(`\\.yk__e--${k} \\{[^}]*animation: ${name} var\\(--blink, 5\\.2s\\) steps\\(1, end\\) var\\(--blink-at, 0s\\) infinite;`), k);
  }
  for (const k of ["0", "l", "r"]) {
    assert.match(css, new RegExp(`\\.yk:not\\(\\[data-look\\]\\) \\.yk__look--${k} \\{[^}]*animation: yk-look-${k} var\\(--look, 16s\\) steps\\(1, end\\) var\\(--look-at, 0s\\) infinite;`), k);
  }
  // the page's tiles and the prompt's peek each have their own
  const page = yukiPage(yukiEntry(null));
  const all = [...page.matchAll(/<svg class="yk[" ][^>]*>/g)].map((m) => clock(m[0])).filter(Boolean);
  assert.ok(all.length >= 3, `${all.length} Yukis with a clock`);
});

